/* Builds the painted background layers into ../assets using headless Chromium.
   Usage:  node tools/build-assets.js            (all themes)
           node tools/build-assets.js 2          (one theme)
   Requires Playwright (npm i -D playwright) */
const path = require('path');
const fs = require('fs');
let chromium;
try { ({ chromium } = require('playwright')); } catch (e) { ({ chromium } = require('/opt/npm-tools/node_modules/playwright')); }

(async () => {
  const theme = process.argv[2];
  const root = path.resolve(__dirname, '..');
  const outDir = path.join(root, 'assets');
  fs.mkdirSync(outDir, { recursive: true });
  const browser = await chromium.launch({ executablePath: process.env.PW_CHROME || (fs.existsSync('/opt/pw-browsers/chromium-1194/chrome-linux/chrome') ? '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' : undefined) });
  const page = await browser.newPage();
  page.on('console', (m) => { if (m.type() === 'error') console.error('page:', m.text()); });
  page.on('pageerror', (e) => console.error('pageerror:', e.message));
  const url = 'file://' + path.join(__dirname, 'generate.html') + (theme != null ? '?theme=' + theme : '');
  await page.goto(url);
  await page.waitForFunction(() => window.DONE === true, null, { timeout: 15 * 60 * 1000 });
  const out = await page.evaluate(() => window.OUT);
  let total = 0;
  for (const [name, dataUrl] of Object.entries(out.files)) {
    const buf = Buffer.from(dataUrl.split(',')[1], 'base64');
    fs.writeFileSync(path.join(outDir, name), buf);
    total += buf.length;
    console.log(name.padEnd(20), (buf.length / 1024).toFixed(0).padStart(6), 'KB');
  }
  // merge manifest with an existing one (when building a single theme)
  const manPath = path.join(outDir, 'manifest.js');
  let manifest = out.manifest;
  if (theme != null && fs.existsSync(manPath)) {
    const txt = fs.readFileSync(manPath, 'utf8');
    const prev = JSON.parse(txt.slice(txt.indexOf('{'), txt.lastIndexOf('}') + 1));
    prev.themes[+theme] = out.manifest.themes[+theme];
    manifest = prev;
  }
  fs.writeFileSync(manPath, '/* generated by tools/build-assets.js */\nwindow.FC_ASSETS = ' + JSON.stringify(manifest) + ';\n');
  console.log('total', (total / 1024 / 1024).toFixed(2), 'MB');
  await browser.close();
})();
